"""Turn Bob's face drawings (face/art) into RGB565 arrays for the ESP32 screen.
Same crop as face.py, so the screen shows exactly the face from the website.
usage: py -3 make_faces_h.py   -> writes ../firmware/bob/bob_faces.h
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "bob", "bob_faces.h")
CROP = (45, 285, 45 + 290, 285 + 290)   # x0, y0, x1, y1 of the face inside the drawing (face.py uses x,y,w,h)
SIZE = 240                               # the round screen
BG = (255, 255, 255)                     # behind the drawing


def frame(name):
    img = Image.open(os.path.join(HERE, "art", f"bob-{name}.png")).convert("RGBA").crop(CROP)
    img = img.resize((SIZE, SIZE), Image.LANCZOS)
    flat = Image.new("RGB", img.size, BG)
    flat.paste(img, mask=img.split()[3])
    return flat


def rgb565(im):
    out = []
    for r, g, b in im.getdata():
        out.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    return out


frames = {n: frame(n) for n in ("idle", "blink", "talk", "lick", "irritated")}
frames["half"] = Image.blend(frames["idle"], frames["blink"], 0.5)   # half-shut eyes, like face.py

with open(OUT, "w") as f:
    f.write("// generated by face/make_faces_h.py from Gokul's drawings. Don't edit by hand\n#pragma once\n#include <stdint.h>\n")
    f.write(f"#define FACE_W {SIZE}\n#define FACE_H {SIZE}\n")
    for name, im in frames.items():
        px = rgb565(im)
        assert len(px) == SIZE * SIZE
        f.write(f"const uint16_t face_{name}[{len(px)}] PROGMEM = {{\n")
        for i in range(0, len(px), 16):
            f.write(",".join(f"0x{p:04X}" for p in px[i:i + 16]) + ",\n")
        f.write("};\n")
    frames["idle"].save(os.path.join(HERE, "screen-idle-240.png"))
print("wrote", os.path.relpath(OUT, HERE), "frames:", list(frames))
