"""Turn meow1-3.wav (and yawn.wav, from make_yawn.py) into 8-bit sound arrays for the ESP32 speaker.
usage: py -3 make_meows_h.py   -> writes ../firmware/bob/bob_meows.h

The ESP32 plays them as PWM on the speaker pin, so each sample is a duty value 0-255
(128 = silence). Each clip fades in from 0 and back out to 0 so the speaker doesn't pop.
"""
import os, wave, struct

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "bob", "bob_meows.h")
RATE_OUT = 11025          # half of the 22050 Hz recordings: plenty for a meow, half the flash
RAMP = 64                 # samples to fade from 0 up to the 128 midpoint (and back down)


def load(name):
    w = wave.open(os.path.join(HERE, name))
    assert w.getnchannels() == 1 and w.getsampwidth() == 2, name
    step = w.getframerate() // RATE_OUT
    raw = struct.unpack(f"<{w.getnframes()}h", w.readframes(w.getnframes()))
    pcm = raw[::step]
    peak = max(1, max(abs(s) for s in pcm))
    body = [max(0, min(255, 128 + round(s / peak * 120))) for s in pcm]
    up = [round(128 * k / RAMP) for k in range(RAMP)]
    return up + body + up[::-1]


clips = [load(f"meow{k}.wav") for k in (1, 2, 3)]
yawn = load("yawn.wav")
with open(OUT, "w") as f:
    f.write("// generated by face/make_meows_h.py from meow1-3.wav and yawn.wav. Don't edit by hand\n#pragma once\n#include <stdint.h>\n")
    f.write(f"#define MEOW_RATE {RATE_OUT}\n")
    for k, c in enumerate(clips):
        f.write(f"const uint8_t meow{k}[{len(c)}] PROGMEM = {{\n")
        for i in range(0, len(c), 24):
            f.write(",".join(str(v) for v in c[i:i + 24]) + ",\n")
        f.write("};\n")
    f.write("const uint8_t *const MEOWS[3] = {meow0, meow1, meow2};\n")
    f.write("const uint32_t MEOW_LEN[3] = {" + ",".join(str(len(c)) for c in clips) + "};\n")
    f.write(f"const uint8_t yawn_snd[{len(yawn)}] PROGMEM = {{\n")
    for i in range(0, len(yawn), 24):
        f.write(",".join(str(v) for v in yawn[i:i + 24]) + ",\n")
    f.write("};\n")
    f.write(f"const uint32_t YAWN_LEN = {len(yawn)};\n")

if __name__ == "__main__":
    for k, c in enumerate(clips + [yawn]):
        assert c[0] == 0 and c[-1] == 0 and min(c) >= 0 and max(c) <= 255
        print(f"{'yawn' if k == 3 else f'meow{k}'}: {len(c)} samples, {len(c) / RATE_OUT:.2f} s")
    print("wrote", OUT)
